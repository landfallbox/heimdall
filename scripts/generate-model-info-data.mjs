// Regenerates src/model-info-data.ts (the bundled fallback model metadata) from
// data/model-info.json, the single source of truth for model info.
//
// Usage:
//   node scripts/generate-model-info-data.mjs          # write src/model-info-data.ts
//   node scripts/generate-model-info-data.mjs --check  # fail if out of sync (used by `npm run check`)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseRemoteModelInfo } from "../src/model-info-schema.ts";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, "data", "model-info.json");
const targetPath = join(root, "src", "model-info-data.ts");

function render(data) {
  return [
    "// Generated by scripts/generate-model-info-data.mjs from data/model-info.json.",
    "// Do not edit by hand: update data/model-info.json and run `npm run modelinfo:generate`.",
    "import type { RemoteModelInfoData } from \"./model-info.ts\";",
    "",
    `export const BUILTIN_MODEL_INFO_DATA: RemoteModelInfoData = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

const data = parseRemoteModelInfo(JSON.parse(readFileSync(sourcePath, "utf8")));
const rendered = render(data);

if (process.argv.includes("--check")) {
  let existing;
  try {
    existing = readFileSync(targetPath, "utf8");
  } catch {
    console.error("src/model-info-data.ts is missing. Run `npm run modelinfo:generate`.");
    process.exit(1);
  }
  // Normalize CRLF so the check passes on Windows checkouts (core.autocrlf).
  if (existing.replace(/\r\n/g, "\n") !== rendered) {
    console.error("src/model-info-data.ts is out of date. Run `npm run modelinfo:generate`.");
    process.exit(1);
  }
  console.log("model-info-data.ts is in sync with data/model-info.json.");
} else {
  writeFileSync(targetPath, rendered, "utf8");
  console.log(`Wrote src/model-info-data.ts (${Object.keys(data.models).length} models).`);
}
