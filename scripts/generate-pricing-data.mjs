// Regenerates src/pricing-data.ts (the bundled fallback pricing tables) from
// data/pricing.json, the single source of truth for model pricing.
//
// Usage:
//   node scripts/generate-pricing-data.mjs          # write src/pricing-data.ts
//   node scripts/generate-pricing-data.mjs --check  # fail if out of sync (used by `npm run check`)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseRemotePricing } from "../src/pricing-updater.ts";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const sourcePath = join(root, "data", "pricing.json");
const targetPath = join(root, "src", "pricing-data.ts");

// Must match PRICING_CATALOG_KEYS in src/usage.ts.
const EXPECTED_CATALOG_KEYS = ["openai", "deepseek", "anthropic", "google", "kimi", "glm", "mimo"];

function render(data) {
  return [
    "// Generated by scripts/generate-pricing-data.mjs from data/pricing.json.",
    "// Do not edit by hand: update data/pricing.json and run `npm run pricing:generate`.",
    "import type { RemotePricingData } from \"./usage.ts\";",
    "",
    `export const BUILTIN_PRICING_DATA: RemotePricingData = ${JSON.stringify(data, null, 2)};`,
    "",
  ].join("\n");
}

const data = parseRemotePricing(JSON.parse(readFileSync(sourcePath, "utf8")));

const keys = Object.keys(data.catalogs).sort();
const expected = [...EXPECTED_CATALOG_KEYS].sort();
if (keys.join(",") !== expected.join(",")) {
  console.error(`data/pricing.json catalogs [${keys.join(", ")}] do not match the built-in catalog keys [${expected.join(", ")}] in src/usage.ts.`);
  process.exit(1);
}

const rendered = render(data);

if (process.argv.includes("--check")) {
  let existing;
  try {
    existing = readFileSync(targetPath, "utf8");
  } catch {
    console.error("src/pricing-data.ts is missing. Run `npm run pricing:generate`.");
    process.exit(1);
  }
  // Normalize CRLF so the check passes on Windows checkouts (core.autocrlf).
  if (existing.replace(/\r\n/g, "\n") !== rendered) {
    console.error("src/pricing-data.ts is out of date. Run `npm run pricing:generate`.");
    process.exit(1);
  }
  console.log("pricing-data.ts is in sync with data/pricing.json.");
} else {
  writeFileSync(targetPath, rendered, "utf8");
  console.log(`Wrote src/pricing-data.ts (${keys.length} catalogs).`);
}
